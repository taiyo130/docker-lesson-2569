#!/usr/bin/env bash
# สร้าง nginx config สำหรับ stdNN.cpedev.cloud (web :8080) และ api-stdNN.cpedev.cloud (api :3000)
# ใช้: bash gen-nginx.sh 0 21 [ssl] > /etc/nginx/sites-available/cpedev-students
set -euo pipefail
FIRST=${1:-0}
LAST=${2:-21}
SSL=${3:-}
CERT=/etc/letsencrypt/live/students.cpedev.cloud

echo "# generated by infra/server/gen-nginx.sh — อย่าแก้ด้วยมือ"
echo "map \$host \$student_backend {"
echo "    hostnames;"
echo "    default \"\";"
for n in $(seq "$FIRST" "$LAST"); do
  name=$(printf "std%02d" "$n")
  ip="10.45.163.$((200 + n))"
  echo "    $name.cpedev.cloud      $ip:8080;"
  echo "    api-$name.cpedev.cloud  $ip:3000;"
done
echo "}"

cat <<'NGINX'

server {
    listen 80;
    server_name ~^(api-)?std\d\d\.cpedev\.cloud$;
NGINX
if [ -n "$SSL" ]; then
cat <<NGINX
    location /.well-known/acme-challenge/ { root /var/www/html; }
    location / { return 301 https://\$host\$request_uri; }
}

server {
    listen 443 ssl;
    server_name ~^(api-)?std\d\d\.cpedev\.cloud\$;
    ssl_certificate     $CERT/fullchain.pem;
    ssl_certificate_key $CERT/privkey.pem;
    include /etc/letsencrypt/options-ssl-nginx.conf;
    ssl_dhparam /etc/letsencrypt/ssl-dhparams.pem;
NGINX
fi
cat <<'NGINX'

    if ($student_backend = "") { return 404; }

    location / {
        proxy_pass http://$student_backend;
        proxy_http_version 1.1;
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection $connection_upgrade_students;
        proxy_connect_timeout 5s;
        # container ยังไม่ได้ deploy → แสดงหน้าอธิบายแทน 502 เปล่าๆ
        proxy_intercept_errors on;
        error_page 502 504 = @not_deployed;
    }

    location @not_deployed {
        default_type text/plain;
        charset utf-8;
        return 502 "$host: ยังไม่มีแอปรันอยู่ (web ต้องเปิด port 8080, api ต้องเปิด port 3000 ใน container)\n";
    }
}

map $http_upgrade $connection_upgrade_students {
    default upgrade;
    ""      close;
}
NGINX
